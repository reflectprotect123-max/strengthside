import {test,expect} from 'playwright/test';
test('Me switch walks Strength to Engine and back; each house keeps its own notebook',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByRole('heading',{name:'Today',exact:true}).waitFor();
 await page.evaluate(()=>setTab('me'));
 const strengthCard=page.locator('.locker-card');
 await expect(strengthCard.getByRole('button',{name:'Strength',exact:true})).toHaveAttribute('aria-pressed','true');
 await strengthCard.getByRole('button',{name:'Engine',exact:true}).click();
 await page.waitForURL(/\/engine\/index\.html$/);
 await page.locator('nav [data-tab="me"]').click();
 await expect(page.getByRole('heading',{name:'Settings',exact:true})).toBeVisible();
 const engineCard=page.locator('.locker-card');await expect(engineCard).toHaveCount(1);
 await expect(engineCard.getByRole('button',{name:'Engine',exact:true})).toHaveAttribute('aria-pressed','true');
 expect(await page.evaluate(()=>[localStorage.getItem('strengthside-standalone-library-v1')!==null,localStorage.getItem('THE-brain-v1')!==null])).toEqual([true,true]);
 await page.evaluate("S.liveWorkout={status:'running'};render()");
 let alerted='';page.once('dialog',d=>{alerted=d.message();d.dismiss();});
 await page.locator('.locker-card').getByRole('button',{name:'Strength',exact:true}).click();
 await expect.poll(()=>alerted).toMatch(/Finish or end the workout/);
 await expect(page).toHaveURL(/\/engine\/index\.html$/);
 await page.evaluate("S.liveWorkout=null;render()");
 await page.locator('.locker-card').getByRole('button',{name:'Strength',exact:true}).click();
 await page.waitForURL(u=>!/\/engine\//.test(u.pathname));
 await expect(page.locator('.locker-card').getByRole('button',{name:'Strength',exact:true})).toHaveAttribute('aria-pressed','true');
 expect(await page.evaluate(()=>S.tab)).toBe('me');
 expect(errors).toEqual([]);
});
